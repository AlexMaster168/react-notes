import { useSyncExternalStore } from 'react'
export type Language = 'ru' | 'uk' | 'en'
export const LANGUAGES: { value: Language; label: string }[] = [
  { value: 'ru', label: 'Русский' },
  { value: 'uk', label: 'Українська' },
  { value: 'en', label: 'English' },
]
function initialLanguage(): Language {
  try {
    const value = localStorage.getItem('react-notes:language')
    return value === 'ru' || value === 'en' ? value : 'uk'
  } catch {
    return 'uk'
  }
}
let language = initialLanguage()
const subscribers = new Set<() => void>()
export function getLanguage() {
  return language
}
export function getLocale() {
  return { ru: 'ru-RU', uk: 'uk-UA', en: 'en-GB' }[language]
}
export function setLanguage(value: Language) {
  language = value
  try {
    localStorage.setItem('react-notes:language', value)
  } catch {
    /* Language can still change for this session. */
  }
  document.documentElement.lang = value
  document.title = t('Дела — задачи и заметки')
  for (const notify of subscribers) notify()
}
function subscribe(callback: () => void) {
  subscribers.add(callback)
  return () => {
    subscribers.delete(callback)
  }
}
export function useLanguage() {
  return useSyncExternalStore(subscribe, getLanguage)
}

